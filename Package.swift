// swift-tools-version:5.10
import PackageDescription

let package = Package(
    name: "AgentMeter",
    defaultLocalization: "en",
    platforms: [.macOS(.v14)],
    products: [
        // The app binary ("Allowance Bar.app/Contents/MacOS/AllowanceBar").
        // Target and module names keep the original AgentMeter naming.
        .executable(name: "AllowanceBar", targets: ["AgentMeter"]),
        // Named case-distinct from the AllowanceBar app binary: on the default
        // case-insensitive APFS, products "AllowanceBar" and "allowancebar"
        // would clobber each other in .build. bundle.sh installs it into the
        // app bundle as Contents/Helpers/allowancebar.
        .executable(name: "allowancebar-cli", targets: ["agentmeter-cli"]),
    ],
    dependencies: [
        .package(url: "https://github.com/sparkle-project/Sparkle", from: "2.6.0"),
    ],
    targets: [
        .target(
            name: "AgentMeterStatusKit",
            path: "Sources/AgentMeterStatusKit"
        ),
        .executableTarget(
            name: "AgentMeter",
            dependencies: [
                "AgentMeterStatusKit",
                .product(name: "Sparkle", package: "Sparkle"),
            ],
            path: "Sources/AgentMeter",
            // The catalog is the editing source; the compiled .lproj strings
            // (regenerated by bundle.sh) ship. Processing both makes Swift
            // Build emit Localizable.strings twice.
            exclude: ["Resources/Localizable.xcstrings"],
            resources: [.process("Resources")]
        ),
        .executableTarget(
            name: "agentmeter-cli",
            dependencies: ["AgentMeterStatusKit"],
            path: "Sources/agentmeter-cli"
        ),
        .testTarget(
            name: "AgentMeterStatusKitTests",
            dependencies: ["AgentMeterStatusKit"],
            path: "Tests/AgentMeterStatusKitTests",
            resources: [.process("Fixtures")]
        ),
        .testTarget(
            name: "AgentMeterTests",
            dependencies: ["AgentMeter", "AgentMeterStatusKit"],
            path: "Tests/AgentMeterTests"
        ),
    ]
)
